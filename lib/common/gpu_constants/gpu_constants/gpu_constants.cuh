inline void createCoefficients(double** devA, double** devB)
{
    gpuErrchk(cudaMalloc((void**)devA, 10 * 9 * sizeof(double)));
    gpuErrchk(cudaMalloc((void**)devB, 10 * 9 * sizeof(double)));

    double aLinear[10 * 9];
    double bLinear[10 * 9];
    for (int i = 0; i < 9; i++) {
        for (int j = 0; j < 10; j++) {
            aLinear[i * 10 + j] = GaussJacksonCoefficients[j][i];
            bLinear[i * 10 + j] = SummedAdamsCoefficients[j][i];
        }
    }
    cublasErrchk(cublasSetMatrix(9, 10, sizeof(double), aLinear, 9, *devA, 9));
    cublasErrchk(cublasSetMatrix(9, 10, sizeof(double), bLinear, 9, *devB, 9));
}

